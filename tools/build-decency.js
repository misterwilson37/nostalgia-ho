#!/usr/bin/env node
// Writes js/decency-words.js from the vendored LDNOOBW lists (tools/ldnoobw,
// CC BY 4.0; see its README.md). Every language file goes in, as written
// (one entry a line, blank lines and stray spaces dropped, duplicates kept
// once); js/decency.js folds them (case, accents, Turkish dotless i) the same
// way it folds a name, at load. Run it again after updating the lists:
//   node tools/build-decency.js
'use strict';
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, 'ldnoobw');
const out = path.join(__dirname, '..', 'js', 'decency-words.js');
const langs = fs.readdirSync(dir).filter(f => /^[a-z]{2,3}(-[A-Za-z0-9-]+)?$/.test(f)).sort();
const lists = {};
for (const l of langs) {
  const seen = new Set();
  lists[l] = fs.readFileSync(path.join(dir, l), 'utf8').split(/\r?\n/).map(s => s.trim().replace(/\s+/g, ' ')).filter(s => s && !seen.has(s) && seen.add(s));
}
const total = Object.values(lists).reduce((a, l) => a + l.length, 0);
const body = `// GENERATED by tools/build-decency.js from tools/ldnoobw: do not edit by hand.
// The "List of Dirty, Naughty, Obscene, and Otherwise Bad Words" by Shutterstock
// and contributors (github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words,
// commit 5faf2ba), CC BY 4.0 (tools/ldnoobw/LICENSE). ${langs.length} languages, ${total} entries.
// Read only by js/decency.js, which js/cloud.js loads when a name is about to
// be shared; the game never loads it otherwise.
(function (root) {
'use strict';
const LISTS = ${JSON.stringify(lists, null, 0).replace(/\],"/g, '],\n"')};
if (typeof module !== 'undefined') module.exports = LISTS; else root.HODECENCY_WORDS = LISTS;
})(this);
`;
fs.writeFileSync(out, body);
console.log(`js/decency-words.js: ${langs.length} languages, ${total} entries, ${(Buffer.byteLength(body) / 1024).toFixed(1)} KiB`);
