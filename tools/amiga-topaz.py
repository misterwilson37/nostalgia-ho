def rows(code):
    g = FONT8X8.get(chr(code))
    # (least significant bit leftmost; the table's rows run from the top, the descenders of g j p q y on the last)
    return [[(by >> x) & 1 for x in range(8)] for by in g] if g else None

def build(name, xw):
    names = ['.notdef', 'space'] + ['uni%04X' % c for c in range(33, 127)]
    glyphs = {}
    adv = {}
    for n in names:
        pen = TTGlyphPen(None)
        if n.startswith('uni'):
            r = rows(int(n[3:], 16))
            if r:
                for y in range(8):
                    for x in range(8):
                        if r[y][x]:
                            # row 0 is the top: the ascent is 6 pixels (Topaz's baseline), 2 below
                            x0, y1 = x * xw, (6 - y) * UNIT; x1, y0 = x0 + xw, y1 - UNIT
                            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
        glyphs[n] = pen.glyph(); adv[n] = (8 * xw, 0)
    fb = FontBuilder(EM, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({c: 'uni%04X' % c for c in range(33, 127)} | {32: 'space'})
    fb.setupGlyf(glyphs); fb.setupHorizontalMetrics(adv)
    fb.setupHorizontalHeader(ascent=12 * UNIT, descent=-4 * UNIT)
    fb.setupNameTable({'familyName': name, 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=12 * UNIT, sTypoDescender=-4 * UNIT, usWinAscent=12 * UNIT, usWinDescent=4 * UNIT)
    fb.setupPost()
    fb.font.flavor = 'woff2'
    out = os.path.join(ROOT, 'assets', 'fonts', name + '.woff2')
    fb.save(out); print(out, os.path.getsize(out))

build('Topaz', UNIT)
build('TopazTall', UNIT // 2)
